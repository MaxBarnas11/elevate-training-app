_SKOMPILOWANE = [(re.compile(w), u, r, n) for w, u, r, n in REGULY]


def _norma(t: str) -> str:
    """Małe litery bez polskich znaków."""
    t = (t or "").lower().replace("ł", "l")
    return "".join(z for z in unicodedata.normalize("NFKD", t) if not unicodedata.combining(z))


def opis(nazwa: str) -> dict[str, str] | None:
    """Opis wykonania dla ćwiczenia albo None, gdy żadna reguła nie pasuje."""
    n = _norma(nazwa)
    for wzor, ustawienie, ruch, uwaga in _SKOMPILOWANE:
        if wzor.search(n):
            return {"ustawienie": ustawienie, "ruch": ruch, "uwaga": uwaga}
    return None
